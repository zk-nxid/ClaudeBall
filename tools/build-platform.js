/* Generates the files the static platform needs, from games.json (the one source of truth):
 *   registry.js   window.ARCADE_GAMES = [...]  (works from file://, where fetch() of JSON is blocked)
 *   sw-files.js   the offline precache list + a content-hash version for the service worker
 * Run: node tools/build-platform.js     (add --check to verify the committed files are up to date)
 * Validates every game: required fields, entry file and cover exist. */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.resolve(__dirname, '..');
const CHECK = process.argv.includes('--check');
const data = JSON.parse(fs.readFileSync(path.join(root, 'games.json'), 'utf8'));
const REQUIRED = ['id', 'title', 'tagline', 'genre', 'entry', 'cover', 'description', 'accent', 'offline', 'controls', 'features', 'storage'];
const problems = [], ids = new Set();
for (const g of data.games) {
  for (const k of REQUIRED) if (g[k] === undefined) problems.push(g.id + ': missing "' + k + '"');
  if (!/^[a-z0-9-]+$/.test(g.id || '')) problems.push('bad id ' + g.id);
  if (ids.has(g.id)) problems.push('duplicate id ' + g.id); ids.add(g.id);
  for (const k of ['entry', 'cover']) if (g[k] && !fs.existsSync(path.join(root, g[k]))) problems.push(g.id + ': ' + k + ' file not found: ' + g[k]);
  if (g.entry && /^(https?:)?\/\//.test(g.entry)) problems.push(g.id + ': entry must be a relative path');
  if (!g.storage || !Array.isArray(g.storage.prefixes) || !g.storage.prefixes.length) problems.push(g.id + ': storage.prefixes required');
}
if (problems.length) { console.error('games.json problems:\n - ' + problems.join('\n - ')); process.exit(1); }

const registry = '/* GENERATED by tools/build-platform.js from games.json - do not edit. */\nwindow.ARCADE_GAMES = ' + JSON.stringify(data.games, null, 2) + ';\n';

// everything the offline cache should hold (static files only; no tests/tools/docs)
const SKIP = /^(\.git|node_modules|tests|tools)(\/|$)|\.md$|^\.gitattributes$|^sw-files\.js$/;
function walk(dir, out) { for (const f of fs.readdirSync(dir)) { const p = path.join(dir, f), rel = path.relative(root, p).split(path.sep).join('/'); if (SKIP.test(rel)) continue; fs.statSync(p).isDirectory() ? walk(p, out) : out.push(rel); } return out; }
if (!CHECK) fs.writeFileSync(path.join(root, 'registry.js'), registry);    // (must exist before hashing)
const files = walk(root, []).sort();
const hash = crypto.createHash('sha1'); for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(root, f))); }
const swfiles = '/* GENERATED by tools/build-platform.js - do not edit. */\nself.ARCADE_VERSION = "' + hash.digest('hex').slice(0, 10) + '";\nself.ARCADE_FILES = ' + JSON.stringify(files, null, 1) + ';\n';
const out = { 'registry.js': registry, 'sw-files.js': swfiles };
for (const [name, text] of Object.entries(out)) {
  const p = path.join(root, name);
  if (CHECK) { if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text) { console.error(name + ' is out of date - run: node tools/build-platform.js'); process.exit(1); } }
  else fs.writeFileSync(p, text);
}
console.log((CHECK ? 'up to date: ' : 'wrote registry.js + sw-files.js: ') + data.games.length + ' games, ' + files.length + ' files');
